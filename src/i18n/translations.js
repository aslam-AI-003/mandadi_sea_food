export function getTranslation(lang, path) {
  const dict = translations[lang] || translations.ta
  const value = path.split(".").reduce((acc, key) => (acc == null ? acc : acc[key]), dict)
  if (value == null) {
    const fallback = path.split(".").reduce((acc, key) => (acc == null ? acc : acc[key]), translations.ta)
    return fallback ?? path
  }
  return value
}
